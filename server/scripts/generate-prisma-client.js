import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * `npm ci` → `prisma generate`, as Prisma 6 and earlier did on install
 * (step 75). Prisma 7 stopped generating the client from @prisma/client's
 * own install script, so on a clean checkout `npm ci` left no client: every
 * import of src/lib/prisma.js failed ("does not provide an export named
 * 'PrismaClient'"), and with it the benchmark workflow, every CI job that
 * imports the app, and the typecheck. Nobody saw it locally, where
 * node_modules still held a client generated by hand long ago.
 *
 * Skipped, not failed, when the schema is not there: the Dockerfile runs
 * `npm ci` before it copies the schema, then generates explicitly.
 *
 * `prisma generate` never connects to a database; prisma.config.js only
 * insists DATABASE_URL is set, so a placeholder is supplied when it is not.
 */
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

if (!existsSync(join(root, "prisma", "schema.prisma"))) {
  console.log("prisma generate skipped: no prisma/schema.prisma here yet");
  process.exit(0);
}

const PLACEHOLDER_URL = "postgresql://generate:generate@localhost:5432/generate";
const prisma = join(root, "node_modules", ".bin", "prisma");
execFileSync(prisma, ["generate"], {
  cwd: root,
  stdio: "inherit",
  // eslint-disable-next-line no-restricted-syntax -- an install script, not the app: config.js does not apply
  env: { ...process.env, DATABASE_URL: process.env.DATABASE_URL || PLACEHOLDER_URL },
});
