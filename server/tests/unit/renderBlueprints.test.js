import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { parse } from "yaml";

/**
 * ops/render/*.render.yaml, the staging and production Blueprints (BUILD-PLAN
 * step 75). Render cannot be asked from a test, so what is checked is what
 * this repository decides: that each Blueprint means what docs/deployment.md
 * §1 says (same image, same config, differing only in DEPLOY_ENV, scale and
 * secrets), that no secret is written into the file, and that every variable
 * is one config.js actually reads. That last one matters more than it looks:
 * config.js strips variables it does not know, so a misspelt key would boot
 * fine and be silently ignored.
 */

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
/** @param {string} env */
const blueprint = (env) =>
  parse(readFileSync(join(ROOT, "ops", "render", `${env}.render.yaml`), "utf8"));
/** @param {any} bp @param {string} type */
const service = (bp, type) => bp.services.find((/** @type {any} */ s) => s.type === type);
/** @param {any} svc */
const envOf = (svc) =>
  Object.fromEntries(svc.envVars.map((/** @type {any} */ v) => [v.key, v]));

const CONFIG_KEYS = new Set(
  [
    ...readFileSync(join(ROOT, "server", "src", "config.js"), "utf8").matchAll(
      /^ {4}([A-Z][A-Z0-9_]+):/gm,
    ),
  ].map((m) => m[1]),
);

/** Values that must come from Render's secret store, never from the file. */
const SECRETS = [
  "ANTHROPIC_API_KEY",
  "EMAIL_PROVIDER_KEY",
  "JWT_SECRET",
  "AUDIT_SALT",
  "METRICS_TOKEN",
  "SENTRY_DSN",
  "ALERT_DRILL_TOKEN",
  "BACKUP_S3_ACCESS_KEY_ID",
  "BACKUP_S3_SECRET_ACCESS_KEY",
];

/** What ops/backup/backup.sh refuses to run without, read from the script itself. */
const BACKUP_SCRIPT_NEEDS = (() => {
  const script = readFileSync(join(ROOT, "ops", "backup", "backup.sh"), "utf8");
  const match = /for name in ([^;]+); do/.exec(script);
  if (!match) throw new Error("backup.sh no longer lists what it needs");
  return match[1].split(/[\s\\]+/).filter(Boolean);
})();

describe.each(["staging", "production"])("ops/render/%s.render.yaml", (env) => {
  const bp = blueprint(env);
  const api = service(bp, "web");
  const vars = envOf(api);

  it("every variable is one config.js reads (an unknown one would be silently dropped)", () => {
    expect(CONFIG_KEYS.size).toBeGreaterThan(30);
    expect(Object.keys(vars).filter((key) => !CONFIG_KEYS.has(key))).toEqual([]);
  });

  it("no secret is written into the file: generated by Render or entered in its dashboard", () => {
    for (const key of SECRETS.filter((k) => k in vars)) {
      expect(vars[key], key).not.toHaveProperty("value");
      expect(vars[key].generateValue === true || vars[key].sync === false, key).toBe(
        true,
      );
    }
    expect(vars.ANTHROPIC_API_KEY.sync).toBe(false);
  });

  it("is the shape the load tests measured and the drain needs", () => {
    expect(api.runtime).toBe("image");
    expect(api.numInstances).toBe(2);
    expect(api.healthCheckPath).toBe("/api/health");
    // NFR-3.5: over the 90 s drain.
    expect(api.maxShutdownDelaySeconds).toBeGreaterThan(90);
    expect(api.maxShutdownDelaySeconds).toBeLessThanOrEqual(300);
    // memory_high divides by this; it must be the plan's real size.
    expect(api.plan).toBe("starter");
    expect(vars.MEMORY_LIMIT_BYTES.value).toBe(String(512 * 1024 * 1024));
    expect(vars.NODE_ENV.value).toBe("production");
    expect(vars.DEPLOY_ENV.value).toBe(env);
    expect(vars.LLM_PROVIDER.value).toBe("anthropic");
    expect(vars.EMAIL_PROVIDER.value).toBe("resend");
  });

  it("keeps the API, its database and its Key Value in one region, the database private to Render", () => {
    const kv = service(bp, "keyvalue");
    expect(kv.region).toBe(api.region);
    expect(bp.databases[0].region).toBe(api.region);
    expect(kv.ipAllowList).toEqual([]);
    expect(kv.maxmemoryPolicy).toBe("noeviction");
    expect(vars.DATABASE_URL.fromDatabase.name).toBe(bp.databases[0].name);
    expect(vars.REDIS_URL.fromService.name).toBe(kv.name);
  });

  it("runs the nightly backup (step 75): the backup image, daily, beside its database", () => {
    const cron = service(bp, "cron");
    expect(cron.name).toBe(`clausecheck-backup-${env}`);
    expect(cron.runtime).toBe("docker");
    expect(cron.dockerfilePath).toBe("ops/backup/Dockerfile");
    // Daily: backup-verify pages at 36 h, so one missed run is noticed.
    expect(cron.schedule).toMatch(/^\d{1,2} \d{1,2} \* \* \*$/);
    expect(cron.region).toBe(bp.databases[0].region);
  });

  it("gives backup.sh everything it refuses to run without, and no secret in the file", () => {
    const cronVars = envOf(service(bp, "cron"));
    expect(BACKUP_SCRIPT_NEEDS).toContain("BACKUP_AGE_RECIPIENT");
    expect(BACKUP_SCRIPT_NEEDS.filter((key) => !(key in cronVars))).toEqual([]);
    expect(cronVars.DATABASE_URL.fromDatabase.name).toBe(bp.databases[0].name);
    for (const key of BACKUP_SCRIPT_NEEDS.filter((k) => k !== "DATABASE_URL")) {
      expect(cronVars[key], key).not.toHaveProperty("value");
      expect(cronVars[key].sync, key).toBe(false);
    }
  });

  it("lets the API list the bucket, with a floor measured from an empty database's dump", () => {
    for (const key of [
      "BACKUP_S3_BUCKET",
      "BACKUP_S3_REGION",
      "BACKUP_S3_ACCESS_KEY_ID",
      "BACKUP_S3_SECRET_ACCESS_KEY",
    ]) {
      expect(vars[key]?.sync, key).toBe(false);
    }
    expect(vars.BACKUP_MIN_BYTES.value).toMatch(/^[1-9]\d*$/);
  });

  it("names every resource for its own environment, so the two can never share one", () => {
    const names = [
      ...bp.services.map((/** @type {any} */ s) => s.name),
      ...bp.databases.map((/** @type {any} */ d) => d.name),
    ];
    for (const name of names) expect(name.endsWith(`-${env}`), name).toBe(true);
  });
});

describe("staging and production differ only where docs/deployment.md §1 allows", () => {
  const staging = blueprint("staging");
  const production = blueprint("production");

  it("the same variables, apart from the staging-only drill token", () => {
    const s = envOf(service(staging, "web"));
    const p = envOf(service(production, "web"));
    expect(Object.keys(s).filter((k) => !(k in p))).toEqual(["ALERT_DRILL_TOKEN"]);
    expect(Object.keys(p).filter((k) => !(k in s))).toEqual([]);
    for (const key of Object.keys(p)) {
      if (
        ["DEPLOY_ENV", "MONTHLY_SPEND_CEILING_USD", "DATABASE_URL", "REDIS_URL"].includes(
          key,
        )
      )
        continue;
      expect(p[key], key).toEqual(s[key]);
    }
  });

  it("production never carries the drill token, the mock, or the sink", () => {
    const p = envOf(service(production, "web"));
    expect(p).not.toHaveProperty("ALERT_DRILL_TOKEN");
    expect(p).not.toHaveProperty("MOCK_LLM_OUTAGE_FILE");
    expect(p).not.toHaveProperty("EMAIL_SINK_DIR");
  });

  it("the privacy policy states the inference geography production actually runs with", () => {
    // config.js ANTHROPIC_INFERENCE_GEO: unset means the workspace default,
    // "global". Changing it without changing the policy, or the reverse, is
    // a published statement that is untrue.
    const p = envOf(service(production, "web"));
    const geo = p.ANTHROPIC_INFERENCE_GEO?.value ?? "global";
    const legal = readFileSync(
      join(ROOT, "client", "src", "legal", "content.js"),
      "utf8",
    );
    if (geo === "us") {
      expect(legal).toMatch(/United States/);
      expect(legal).not.toMatch(/default “global” processing/);
    } else {
      expect(legal).toMatch(/default “global” processing/);
    }
  });
});
